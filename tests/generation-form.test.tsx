import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { GenerationForm } from "@/components/dashboard/generation-form";
import { tailoringInput, savedResume } from "./fixtures/tailoring";
vi.mock("@/lib/generation/client", () => ({ requestTailoredResume: vi.fn(), requestResumeValidation: vi.fn() }));
vi.mock("@/lib/storage/resumes", () => ({ saveGeneratedResume: vi.fn(), updateGeneratedResume: vi.fn() }));
vi.mock("@/lib/storage/database", () => ({ getDatabase: vi.fn(), readProfile: vi.fn() }));
import { requestTailoredResume, requestResumeValidation } from "@/lib/generation/client";
import { saveGeneratedResume, updateGeneratedResume } from "@/lib/storage/resumes";
import { readProfile } from "@/lib/storage/database";
beforeEach(() => { vi.resetAllMocks(); vi.mocked(readProfile).mockResolvedValue(tailoringInput().profile); });
afterEach(() => vi.restoreAllMocks());
it("retries a failed local save without repeating AI generation", async () => {
  const resume = savedResume();
  vi.mocked(requestTailoredResume).mockResolvedValue({ resume, reviewPermit: "reserved" });
  vi.mocked(saveGeneratedResume).mockRejectedValueOnce(new Error("Browser storage is full.")).mockResolvedValueOnce(resume);
  vi.mocked(requestResumeValidation).mockResolvedValue(resume);
  vi.mocked(updateGeneratedResume).mockResolvedValue({ id: resume.id, updatedAt: resume.updatedAt, content: resume, originalContent: resume });
  render(<GenerationForm profile={tailoringInput().profile} />);
  fireEvent.change(screen.getByLabelText("Job description", { exact: true }), { target: { value: "React engineer building accessible web applications." } });
  fireEvent.click(screen.getByRole("button", { name: "Generate Tailored Resume" }));
  expect(await screen.findByRole("alert")).toHaveTextContent("storage is full");
  expect(screen.getByRole("button", { name: "Generate Tailored Resume" })).toBeDisabled();
  fireEvent.click(screen.getByRole("button", { name: "Retry saving resume" }));
  await waitFor(() => expect(requestResumeValidation).toHaveBeenCalledTimes(1));
  await waitFor(() => expect(updateGeneratedResume).toHaveBeenCalledTimes(1));
  expect(requestTailoredResume).toHaveBeenCalledTimes(1);
  expect(saveGeneratedResume).toHaveBeenCalledTimes(2);
  expect(screen.getByRole("link", { name: "Open saved resume" })).toHaveAttribute("href", `/resume/${resume.id}`);
});
it("prevents duplicate submissions while processing", async () => {
  vi.mocked(requestTailoredResume).mockReturnValue(new Promise(() => {}));
  render(<GenerationForm profile={tailoringInput().profile} />);
  fireEvent.change(screen.getByLabelText("Job description", { exact: true }), { target: { value: "React engineer building accessible web applications." } });
  const button = screen.getByRole("button", { name: "Generate Tailored Resume" });
  fireEvent.click(button); fireEvent.click(button);
  await waitFor(() => expect(requestTailoredResume).toHaveBeenCalledTimes(1));
  expect(screen.getByRole("button", { name: "Processing…" })).toBeDisabled();
});

it("saves before review and retries only factual validation after a rate or network error", async () => {
  const resume = savedResume();
  vi.mocked(requestTailoredResume).mockResolvedValue({ resume, reviewPermit: "reserved" });
  vi.mocked(saveGeneratedResume).mockResolvedValue(resume);
  vi.mocked(requestResumeValidation).mockImplementationOnce(async () => {
    expect(saveGeneratedResume).toHaveBeenCalledTimes(1);
    throw new Error("Review service is unavailable.");
  }).mockResolvedValueOnce(resume);
  vi.mocked(updateGeneratedResume).mockResolvedValue({ id: resume.id, updatedAt: resume.updatedAt, content: resume, originalContent: resume });
  render(<GenerationForm profile={tailoringInput().profile} />);
  fireEvent.change(screen.getByLabelText("Job description", { exact: true }), { target: { value: "React engineer building accessible web applications." } });
  fireEvent.click(screen.getByRole("button", { name: "Generate Tailored Resume" }));
  expect(await screen.findByRole("alert")).toHaveTextContent("Review service is unavailable");
  expect(screen.getByRole("link", { name: "Open saved resume" })).toBeVisible();
  fireEvent.click(screen.getByRole("button", { name: "Retry factual review" }));
  await waitFor(() => expect(updateGeneratedResume).toHaveBeenCalledTimes(1));
  expect(requestTailoredResume).toHaveBeenCalledTimes(1);
  expect(saveGeneratedResume).toHaveBeenCalledTimes(1);
  expect(requestResumeValidation).toHaveBeenCalledTimes(2);
  expect(vi.mocked(requestResumeValidation).mock.calls[1][4]).toBe("reserved");
});
