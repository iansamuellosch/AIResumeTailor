import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { tailoringInput, selection } from "../tests/fixtures/tailoring";
import { assembleResume } from "../src/lib/generation/assemble";
import { selectEvidence } from "../src/lib/generation/evidence";
import mammoth from "mammoth";
import { PDFDocument } from "pdf-lib";

for (const layout of ["Modern", "Classic", "Compact"]) {
test(`${layout}: upload, approve, tailor, validate, edit, export both formats, and recover locally`, async ({ page }, testInfo) => {
  test.setTimeout(90000);
  const input = tailoringInput(); const draft = { ...input.profile, status: "draft", verifiedAt: undefined };
  await page.route("**/api/parse-resume", (route) => route.fulfill({ json: { success: true, data: { profile: draft } } }));
  await page.route("**/api/analyze-job", (route) => route.fulfill({ json: { success: true, data: { jobAnalysis: input.jobAnalysis } } }));
  await page.route("**/api/generate-resume", async (route) => { const body = { ...route.request().postDataJSON(), jobAnalysis: input.jobAnalysis }; const resume = assembleResume(body, selectEvidence(body.profile, body.jobAnalysis, body.settings), selection()); await route.fulfill({ json: { success: true, data: { resume } } }); });
  let reviewCalls = 0;
  await page.route("**/api/validate-resume", async (route) => { reviewCalls++; const { resume } = route.request().postDataJSON(); await route.fulfill({ json: { success: true, data: { resume: { ...resume, validation: { status: "passed", checkedAt: new Date().toISOString(), issues: [] } } } } }); });
  await page.goto("/");
  await expect(page.getByLabel("Choose a resume file")).toBeEnabled();
  await page.getByLabel("Choose a resume file").setInputFiles("e2e/fixtures/resume.pdf");
  await expect(page).toHaveURL(/\/profile$/, { timeout: 45000 });
  await expect(page.getByLabel("Full name", { exact: true })).toHaveValue("Alex Doe");
  const jump = page.locator("summary").filter({ hasText: "Jump to section" });
  if (await jump.isVisible()) await jump.click();
  await page.getByRole("navigation", { name: "Profile sections" }).getByRole("link", { name: /^Work experience/ }).click();
  await page.getByRole("group", { name: "Employment 1", exact: true }).getByLabel("Employer", { exact: true }).fill("Reviewed Example Company");
  await page.getByRole("button", { name: "Save & Continue", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.getByLabel("Job description", { exact: true }).fill("Seeking a React engineer to integrate REST APIs and build accessible applications.");
  await page.getByRole("radio", { name: layout, exact: true }).press("Space");
  await expect(page.getByRole("radio", { name: layout, exact: true })).toBeChecked();
  await page.getByRole("button", { name: "Generate Tailored Resume" }).click();
  await page.getByRole("link", { name: "Open saved resume", exact: true }).click();
  await expect(page.getByRole("article", { name: "Saved resume" })).toContainText("Reviewed Example Company");
  await page.getByRole("button", { name: "Edit resume", exact: true }).click();
  await page.getByLabel("Professional summary", { exact: true }).fill("Develops applications with React.");
  await expect(page.getByRole("button", { name: "Download PDF", exact: true })).toBeDisabled();
  await expect(page.getByRole("article", { name: "Saved resume" })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("resume-editor.png"), fullPage: true });
  await expect(page.getByRole("button", { name: /Check facts|Recheck facts/ })).toHaveCount(0);
  await page.getByRole("button", { name: "Save edits", exact: true }).click();
  await expect(page.getByRole("region", { name: "Resume text editor" })).toHaveCount(0);
  await expect(page.getByRole("article", { name: "Saved resume" })).toContainText("Develops applications with React.");
  expect(reviewCalls).toBe(1);
  await expect(page.getByRole("region", { name: "Factual validation" })).toHaveCount(0);
  const pdfDownload = page.waitForEvent("download"); await page.getByRole("button", { name: "Download PDF", exact: true }).click();
  const pdf = await pdfDownload; expect(pdf.suggestedFilename()).toBe("Alex_Doe_Frontend_Engineer.pdf");
  const pdfBytes = await readFile((await pdf.path())!); expect(pdfBytes.subarray(0, 4).toString()).toBe("%PDF"); expect((await PDFDocument.load(pdfBytes)).getPageCount()).toBeGreaterThan(0);
  const docxDownload = page.waitForEvent("download"); await page.getByRole("button", { name: "Download Word", exact: true }).click();
  const docx = await docxDownload; expect(docx.suggestedFilename()).toBe("Alex_Doe_Frontend_Engineer.docx");
  const text = await mammoth.extractRawText({ buffer: await readFile((await docx.path())!) }); expect(text.value).toContain("Reviewed Example Company"); expect(text.value).toContain("Develops applications with React.");
  await page.reload(); await expect(page.getByRole("article", { name: "Saved resume" })).toContainText("Develops applications with React.");
  await expect(page.getByRole("button", { name: "Download PDF", exact: true })).toBeEnabled();
  expect(reviewCalls).toBe(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("resume-preview.png"), fullPage: true });
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
});

}

test("profile backups import for review and destructive actions require confirmation", async ({ page }, testInfo) => {
  const profile = tailoringInput().profile;
  await page.goto("/settings");
  await page.getByLabel("Restore a profile backup", { exact: true }).setInputFiles({ name: "profile.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(profile)) });
  await expect(page).toHaveURL(/\/profile$/); await expect(page.getByLabel("Full name", { exact: true })).toHaveValue("Alex Doe");
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Settings", exact: true }).click();
  const draftDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download profile backup", exact: true }).click();
  const draftBackup = JSON.parse(await readFile((await (await draftDownload).path())!, "utf8"));
  expect(draftBackup.unfinishedProfile.status).toBe("draft");
  expect(draftBackup.unfinishedProfile.personalInfo.fullName).toBe("Alex Doe");
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Profile", exact: true }).click();
  await page.getByRole("button", { name: "Save & Continue", exact: true }).click(); await expect(page).toHaveURL(/\/dashboard$/);
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Settings", exact: true }).click();
  await expect(page.getByRole("main")).not.toContainText("IndexedDB");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("settings.png"), fullPage: true });
  const pending = page.waitForEvent("download"); await page.getByRole("button", { name: "Download profile backup", exact: true }).click();
  const backup = JSON.parse(await readFile((await (await pending).path())!, "utf8")); expect(backup.approvedProfile.personalInfo.fullName).toBe("Alex Doe");
  expect(backup.unfinishedProfile).toBeUndefined();
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Profile", exact: true }).click();
  await page.getByLabel("Full name", { exact: true }).fill("Alex Doe — unfinished edit");
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Settings", exact: true }).click();
  const combinedDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download profile backup", exact: true }).click();
  const combinedBackup = JSON.parse(await readFile((await (await combinedDownload).path())!, "utf8"));
  expect(combinedBackup.approvedProfile.personalInfo.fullName).toBe("Alex Doe");
  expect(combinedBackup.unfinishedProfile.personalInfo.fullName).toBe("Alex Doe — unfinished edit");
  await expect(page.getByRole("button", { name: /^Download/ })).toHaveCount(1);
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByLabel("Restore a profile backup", { exact: true }).setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(combinedBackup)) });
  await expect(page).toHaveURL(/\/profile$/);
  await expect(page.getByLabel("Full name", { exact: true })).toHaveValue("Alex Doe — unfinished edit");
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Settings", exact: true }).click();
  await page.getByLabel("Restore a profile backup", { exact: true }).setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from('{"invalid":true}') });
  await expect(page.getByRole("alert", { name: "Local data error" })).toContainText("not a supported profile backup");
  const cancelRestore = page.waitForEvent("dialog");
  await page.getByLabel("Restore a profile backup", { exact: true }).setInputFiles({ name: "replacement.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(profile)) });
  await (await cancelRestore).dismiss();
  await expect(page.getByRole("button", { name: "Download profile backup", exact: true })).toBeEnabled();
  await expect(page).toHaveURL(/\/settings$/);
  page.once("dialog", (dialog) => dialog.dismiss()); await page.getByRole("button", { name: "Delete all local data", exact: true }).click(); await expect(page).toHaveURL(/\/settings$/);
  page.once("dialog", (dialog) => dialog.accept()); await page.getByRole("button", { name: "Delete uploaded resumes", exact: true }).click(); await expect(page.getByRole("status", { name: "Local data status" })).toContainText("Uploaded files deleted");
  page.once("dialog", (dialog) => dialog.accept()); await page.getByRole("button", { name: "Delete generated resumes", exact: true }).click(); await expect(page.getByRole("status", { name: "Local data status" })).toContainText("Saved resumes deleted");
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
});
